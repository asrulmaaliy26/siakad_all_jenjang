    <h1 class="text-2xl font-bold tracking-tight text-gray-900 dark:text-gray-100 mb-4">Alur Perubahan Semester & Persetujuan KRS (Panduan DPA/Wali Dosen)</h1>
    
    <p class="mb-6">Dokumen ini menjelaskan prosedur bagi Dosen Pembimbing Akademik (DPA) untuk mengelola transisi semester mahasiswa dan memberikan persetujuan KRS.</p>

    <hr class="my-6 border-gray-200 dark:border-gray-700">

    <h2 class="text-xl font-semibold text-gray-900 dark:text-gray-100 mb-4 flex items-center gap-2">
        <span>🔄</span> 1. Alur Transisi Ke Semester Baru
    </h2>

    <p class="mb-4">Proses ini dilakukan ketika mahasiswa telah menyelesaikan semester berjalan dan siap masuk ke semester berikutnya.</p>

    <h3 class="text-lg font-medium text-gray-900 dark:text-gray-100 mb-2">Langkah-langkah:</h3>
    <ol class="list-decimal list-inside mb-6 space-y-3 ml-4 text-gray-700 dark:text-gray-300">
        <li><strong>Buka Menu KRS</strong>: Masuk ke sidebar <strong>Perkuliahan > KRS</strong>.</li>
        <li><strong>Filter Mahasiswa</strong>: Gunakan filter "Wali Dosen" untuk menampilkan hanya mahasiswa bimbingan Anda.</li>
        <li><strong>Cek Kelayakan</strong>: Pastikan mahasiswa sudah melunasi pembayaran (<strong>Status Bayar: Lunas</strong>) dan berstatus <strong>Aktif</strong>.</li>
        <li>
            <strong>Nonaktifkan Semester Lama</strong>: 
            <ul class="list-disc list-inside mt-2 ml-6 space-y-1">
                <li>Pada kolom <strong>Status Aktif</strong>, ubah pilihan dari "Aktif" menjadi <strong>"Tidak Aktif"</strong>.</li>
                <li>
                    <strong>Sistem Otomatis</strong>: Secara instan, sistem akan:
                    <ul class="list-disc list-inside mt-1 ml-6 space-y-0.5 opacity-80">
                        <li>Menghitung IPS (Indeks Prestasi Semester) terakhir mahasiswa.</li>
                        <li>Menentukan batas maksimal SKS untuk semester depan (24/18/12 SKS).</li>
                        <li>Membuatkan baris <strong>Akademik KRS Baru</strong> secara otomatis dengan status "Aktif".</li>
                        <li>Baris lama akan berpindah status menjadi "Tidak Aktif".</li>
                    </ul>
                </li>
            </ul>
        </li>
    </ol>

    <hr class="my-6 border-gray-200 dark:border-gray-700">

    <h2 class="text-xl font-semibold text-gray-900 dark:text-gray-100 mb-4 flex items-center gap-2">
        <span>✅</span> 2. Prosedur Persetujuan (Approval) KRS
    </h2>

    <p class="mb-4">Setelah semester baru dibuat, mahasiswa akan mulai mengisi rencana studinya. Tugas DPA adalah memvalidasi pilihan tersebut.</p>

    <h3 class="text-lg font-medium text-gray-900 dark:text-gray-100 mb-2">Langkah-langkah:</h3>
    <ol class="list-decimal list-inside mb-6 space-y-3 ml-4 text-gray-700 dark:text-gray-300">
        <li>
            <strong>Cek Mata Kuliah</strong>: 
            <ul class="list-disc list-inside mt-2 ml-6 space-y-1">
                <li>Klik tombol <strong>Aksi (Titik Tiga)</strong> pada baris KRS mahasiswa yang berstatus "Aktif".</li>
                <li>Pilih menu <strong>"Mata Pelajaran"</strong> (Ikon: Buku Terbuka 📖).</li>
                <li>Tinjau daftar mata kuliah yang diambil mahasiswa, apakah sudah sesuai dengan kurikulum dan sebaran mata kuliah.</li>
            </ul>
        </li>
        <li>
            <strong>Diskusi (Jika Perlu)</strong>: 
            <ul class="list-disc list-inside mt-2 ml-6 space-y-1">
                <li>Jika ada keraguan, gunakan tombol <strong>"Diskusi Pembimbing"</strong> (Ikon: Chat 💬) di bagian atas tabel untuk berkomunikasi dengan mahasiswa.</li>
            </ul>
        </li>
        <li>
            <strong>Berikan Persetujuan</strong>: 
            <ul class="list-disc list-inside mt-2 ml-6 space-y-1">
                <li>Jika sudah sesuai, pada kolom <strong>Syarat KRS</strong>, ubah status dari "Menunggu Persetujuan" menjadi <strong>"Disetujui"</strong>.</li>
                <li><strong>Dampaknya</strong>: KRS akan <strong>Terkunci (Locked)</strong>. Mahasiswa tidak bisa menambah atau menghapus mata kuliah lagi. Nama mahasiswa akan muncul di daftar absensi pengajar.</li>
            </ul>
        </li>
    </ol>

    <hr class="my-6 border-gray-200 dark:border-gray-700">

    <h2 class="text-xl font-semibold text-gray-900 dark:text-gray-100 mb-4 flex items-center gap-2">
        <span>⚠️</span> 3. Pembatalan Persetujuan (Unlocking KRS)
    </h2>

    <p class="mb-4">Jika terdapat kesalahan atau mahasiswa ingin mengubah mata kuliah setelah terlanjur disetujui:</p>

    <ol class="list-decimal list-inside mb-6 space-y-3 ml-4 text-gray-700 dark:text-gray-300">
        <li>
            <strong>Batalkan Persetujuan</strong>: 
            <ul class="list-disc list-inside mt-2 ml-6 space-y-1">
                <li>Pada kolom <strong>Syarat KRS</strong>, ubah kembali status dari "Disetujui" menjadi <strong>"Menunggu Persetujuan"</strong>.</li>
            </ul>
        </li>
        <li>
            <strong>Edit Kembali</strong>: 
            <ul class="list-disc list-inside mt-2 ml-6 space-y-1">
                <li>Setelah status berubah, KRS akan kembali <strong>Terbuka (Unlocked)</strong>.</li>
                <li>Mahasiswa dapat menghapus atau menambah mata kuliah baru melalui portal mereka.</li>
            </ul>
        </li>
        <li>
            <strong>Setujui Kembali</strong>: 
            <ul class="list-disc list-inside mt-2 ml-6 space-y-1">
                <li>Setelah revisi selesai dilakukan oleh mahasiswa, silakan cek ulang dan ubah kembali status ke <strong>"Disetujui"</strong> untuk mengunci data secara permanen.</li>
            </ul>
        </li>
    </ol>

    <hr class="my-6 border-gray-200 dark:border-gray-700">

    <h2 class="text-xl font-semibold text-gray-900 dark:text-gray-100 mb-4 flex items-center gap-2">
        <span>📌</span> Ketentuan Penting
    </h2>

    <ul class="list-disc list-inside mb-6 space-y-2 ml-4 text-gray-700 dark:text-gray-300">
        <li><strong>Gagal Deaktif</strong>: Jika DPA mencoba menonaktifkan KRS tapi mahasiswa belum bayar (Status Bayar: Belum Lunas), sistem akan menolak dan memberikan notifikasi error.</li>
        <li><strong>IPS Penentu SKS</strong>: Batas SKS di KRS baru ditentukan secara otomatis oleh sistem berdasarkan rata-rata nilai semester yang baru saja dinonaktifkan.</li>
    </ul>
